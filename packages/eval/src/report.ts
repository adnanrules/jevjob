// Renders metrics as a markdown report. The README links to these files instead of copying numbers by hand.
import { TIER_ORDER } from "@jevjob/core";
import { formatRate, type CaseResult, type Metrics } from "./metrics";

export interface RunInfo {
  system: string;
  commit: string;
  dirty: boolean;
}

const ROWS: Array<[string, (m: Metrics) => string]> = [
  ["Tier accuracy (exact)", (m) => formatRate(m.tierAccuracy)],
  ["Within one tier", (m) => formatRate(m.withinOneTier)],
  ["False-skip rate ↓", (m) => formatRate(m.falseSkip)],
  ["False-apply rate ↓", (m) => formatRate(m.falseApply)],
  ["Blocker recall", (m) => formatRate(m.blockerRecall)],
  ["Blocker precision", (m) => formatRate(m.blockerPrecision)],
  ["Requirement checks correct", (m) => formatRate(m.requirementChecks)],
  ["Checked lines not extracted ↓", (m) => String(m.notExtracted)],
  ["Mean latency per job", (m) => (m.meanLatencyMs === null ? "n/a (cached)" : `${m.meanLatencyMs.toFixed(2)} ms`)],
  ["External calls per job", (m) => m.callsPerJob.toFixed(1)],
  ["Input tokens per job", (m) => Math.round(m.inputTokensPerJob).toLocaleString("en-US")],
];

export function renderMarkdown(info: RunInfo, splits: Record<"test" | "dev" | "all", Metrics>, results: CaseResult[]): string {
  const header = `| Metric | test (n=${splits.test.cases}) | dev (n=${splits.dev.cases}) | all (n=${splits.all.cases}) |`;
  const table = [header, "|---|---|---|---|", ...ROWS.map(([name, f]) => `| ${name} | ${f(splits.test)} | ${f(splits.dev)} | ${f(splits.all)} |`)];

  const confusion = [
    `| expected ↓ / predicted → | ${TIER_ORDER.join(" | ")} |`,
    `|---|${TIER_ORDER.map(() => "---").join("|")}|`,
    ...TIER_ORDER.map((e) => {
      const m = splits.test.cases ? splits.test : splits.dev;
      return `| **${e}** | ${TIER_ORDER.map((p) => m.confusion[e][p] || "·").join(" | ")} |`;
    }),
  ];

  const misses = results
    .filter((r) => r.expected.tier !== r.predicted.tier)
    .map((r) => `| ${r.split} | ${r.id} | ${r.expected.tier} | ${r.predicted.tier} |`);

  const wrongChecks = results.flatMap((r) =>
    r.checks
      .filter((c) => c.predicted !== c.expected)
      .map((c) => `| ${r.split} | ${r.id} | ${c.requirement} | ${c.expected} | ${c.predicted ?? "not extracted"} |`),
  );

  return [
    `# Eval results: \`${info.system}\``,
    "",
    `Commit \`${info.commit}\`${info.dirty ? " (with uncommitted changes)" : ""}. Generated by \`npm run eval\`; don't edit by hand.`,
    "",
    "Only **test** (`heldout.json`) is a fair measurement. **dev** (`cases.json`) was used for tuning, so its scores are optimistic.",
    "",
    ...table,
    "",
    `## Confusion matrix (${splits.test.cases ? "test" : "dev"})`,
    "",
    ...confusion,
    "",
    "## Wrong tiers",
    "",
    ...(misses.length ? ["| split | case | expected | predicted |", "|---|---|---|---|", ...misses] : ["None."]),
    "",
    "## Wrong requirement checks",
    "",
    ...(wrongChecks.length
      ? ["| split | case | line | expected | predicted |", "|---|---|---|---|---|", ...wrongChecks]
      : ["None."]),
    "",
  ].join("\n");
}
